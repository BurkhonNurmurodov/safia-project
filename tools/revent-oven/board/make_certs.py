#!/usr/bin/env python3
"""Write src/board/certs.h — the root certificates the board trusts for IMS.

production.safiacorporate.uz is behind Cloudflare, whose certificates come from
Google Trust Services (today: WE1 → GTS Root R4), Let's Encrypt or SSL.com;
the origin's own certificate is Let's Encrypt. Every root those use is listed,
so a change of CA at Cloudflare does not lock the board out. Read from this
Mac's store (/etc/ssl/cert.pem); re-run when a root nears its end date.
"""
import os
import re
import subprocess
import sys

WANT = ["GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4", "GlobalSign Root CA",
        "ISRG Root X1", "ISRG Root X2",
        "SSL.com Root Certification Authority ECC", "SSL.com Root Certification Authority RSA",
        "SSL.com TLS ECC Root CA 2022", "SSL.com TLS RSA Root CA 2022"]
STORE = "/etc/ssl/cert.pem"


def main():
    pem = open(STORE).read()
    blocks = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S)
    got = {}
    for b in blocks:
        out = subprocess.run(["openssl", "x509", "-noout", "-subject", "-enddate"], input=b,
                             capture_output=True, text=True).stdout
        for w in WANT:
            if w not in got and re.search(r"CN\s*=\s*" + re.escape(w) + r"\s*(,|\n|$)", out):
                end = re.search(r"notAfter=(.*)", out).group(1).strip()
                got[w] = (b, end)
    lines = ["// Generated by make_certs.py from " + STORE + " — do not edit by hand.",
             "// The roots the board trusts for IMS (Cloudflare / origin certificate CAs).",
             "#pragma once", "", "static const char ROOT_CAS[] ="]
    for w in WANT:
        if w not in got:
            print("not in the store, left out:", w, file=sys.stderr)
            continue
        b, end = got[w]
        lines.append("    // %s — valid until %s" % (w, end))
        for ln in b.strip().splitlines():
            lines.append('    "%s\\n"' % ln)
    lines[-1] += ";"
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "board", "certs.h")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path, "with", len(got), "roots")


if __name__ == "__main__":
    main()
