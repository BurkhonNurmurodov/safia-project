// «Tashkiliy tuzilma» (/panel/orgchart) — the page's words in the four
// platform languages, beside the page (the /people pattern). `fill(s, {n})`
// puts the numbers in. Role names, page names, capability names and the two
// grant scopes come from the platform's own keys (t()), never from here.

export const fill = (s, vars) =>
  String(s ?? "").replace(/\{(\w+)\}/g, (_, k) => (vars?.[k] ?? `{${k}}`));

