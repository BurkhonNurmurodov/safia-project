// «Hisobotlar» (/reports) — the page's words in the four platform languages,
// beside the page (the /ontime and /turnover pattern). `fill(s, {n: 3})` puts
// the numbers in.
//
// The SERVER sends figures under stable keys and the words live here, so one
// computation serves four languages — and the export posts these same strings
// back, which is how the document can never name something the screen does not
// (services/grid_export.py's rule).

export const fill = (s, vars) =>
  String(s ?? "").replace(/\{(\w+)\}/g, (_, k) => (vars?.[k] ?? `{${k}}`));

